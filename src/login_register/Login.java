    private void userLogin(String username, String password) {

        String sql = "SELECT * FROM users "
                + "WHERE username = ? "
                + "AND password_hash = ? "
                + "AND status = 'active'";

        try {
            // Convert the entered password to a SHA-256 hash
            MessageDigest md = MessageDigest.getInstance("SHA-256");

            byte[] hashBytes = md.digest(
                    password.getBytes(StandardCharsets.UTF_8)
            );

            String hashedPassword = HexFormat.of().formatHex(hashBytes);

            try (Connection dbconn = DBConnection.connectDB()) {

                if (dbconn == null) {
                    JOptionPane.showMessageDialog(
                            this,
                            "Database connection failed!",
                            "Error",
                            JOptionPane.ERROR_MESSAGE
                    );
                    return;
                }

                try (PreparedStatement st = dbconn.prepareStatement(sql)) {

                    st.setString(1, username);
                    st.setString(2, hashedPassword);

                    try (ResultSet res = st.executeQuery()) {

                        if (res.next()) {
                            JOptionPane.showMessageDialog(
                                    this,
                                    "Welcome, " + res.getString("full_name") + "!"
                            );

                            dispose();

                            Dashboard d = new Dashboard();
                            d.setTitle("Dashboard");
                            d.setLocationRelativeTo(null);
                            d.setVisible(true);

                        } else {
                            JOptionPane.showMessageDialog(
                                    this,
                                    "Invalid username or password!",
                                    "Login Failed",
                                    JOptionPane.ERROR_MESSAGE
                            );
                        }
                    }
                }
            }

        } catch (SQLException | NoSuchAlgorithmException ex) {
            ex.printStackTrace();

            JOptionPane.showMessageDialog(
                    this,
                    "Login error: " + ex.getMessage(),
                    "Error",
                    JOptionPane.ERROR_MESSAGE
            );
        }
    }

