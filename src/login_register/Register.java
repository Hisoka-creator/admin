    private void btnRegisterActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegisterActionPerformed
        // TODO add your handling code here:
        
        String fullName = tfFullName.getText().trim();
        String username = tfUsername.getText().trim();
        String email = tfEmail.getText().trim();

        String password = new String(pfPassword.getPassword());
        String confirmPassword = new String(pfConfirmPassword.getPassword());

        // 1. Check required fields
        if (fullName.isEmpty() || username.isEmpty() || email.isEmpty()
                || password.isEmpty() || confirmPassword.isEmpty()) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Please fill in all fields.",
                    "Missing Information",
                    javax.swing.JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        if (!email.matches("^[A-Za-z0-9+_.-]+@[A-Za-z0-9.-]+\\.[A-Za-z]{2,}$")) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Please enter a valid email address.",
                    "Invalid Email",
                    javax.swing.JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        if (password.length() < 8) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Password must contain at least 8 characters.",
                    "Weak Password",
                    javax.swing.JOptionPane.WARNING_MESSAGE
            );
            return;
        }
       
        if (!password.equals(confirmPassword)) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Passwords do not match.",
                    "Password Error",
                    javax.swing.JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        String passwordHash;

        try {
            java.security.MessageDigest md =
                    java.security.MessageDigest.getInstance("SHA-256");

            byte[] hashBytes = md.digest(
                    password.getBytes(java.nio.charset.StandardCharsets.UTF_8)
            );

            passwordHash = java.util.HexFormat.of().formatHex(hashBytes);

        } catch (java.security.NoSuchAlgorithmException ex) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Unable to process the password.",
                    "System Error",
                    javax.swing.JOptionPane.ERROR_MESSAGE
            );
            return;
        }

        String sql = "INSERT INTO users "
                + "(role_id, username, password_hash, full_name, email, status) "
                + "VALUES (?, ?, ?, ?, ?, 'active')";

        try (java.sql.Connection con = DBConnection.connectDB();
             java.sql.PreparedStatement pst = con.prepareStatement(sql)) {

            if (con == null) {
                javax.swing.JOptionPane.showMessageDialog(
                        this,
                        "Unable to connect to the database.",
                        "Connection Error",
                        javax.swing.JOptionPane.ERROR_MESSAGE
                );
                return;
            }

            pst.setInt(1, 1);
            pst.setString(2, username);
            pst.setString(3, passwordHash);
            pst.setString(4, fullName);
            pst.setString(5, email);

            int rowsInserted = pst.executeUpdate();

            if (rowsInserted > 0) {
                javax.swing.JOptionPane.showMessageDialog(
                        this,
                        "Admin account registered successfully!",
                        "Registration Successful",
                        javax.swing.JOptionPane.INFORMATION_MESSAGE
                );

                Login loginForm = new Login();
                loginForm.setLocationRelativeTo(null);
                loginForm.setVisible(true);
                this.dispose();
            }

        } catch (java.sql.SQLIntegrityConstraintViolationException ex) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "That username or email may already be registered.",
                    "Duplicate Account",
                    javax.swing.JOptionPane.WARNING_MESSAGE
            );

        } catch (java.sql.SQLException ex) {
            java.util.logging.Logger.getLogger(Register.class.getName())
                    .log(java.util.logging.Level.SEVERE, null, ex);

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Registration failed. Please check your database connection and table columns.",
                    "Database Error",
                    javax.swing.JOptionPane.ERROR_MESSAGE
            );
        }
    
    }//GEN-LAST:event_btnRegisterActionPerformed

